// Package sdkcheck checks a language SDK release against plunge's resource monitor: the engine features
// the SDK asks about, and the CLI version it requires.
//
// An SDK learns what the engine supports in two ways. Current SDKs call GetDeploymentInfo and read its
// SupportedFeatures, a list of ResourceMonitorFeature enum values. Older SDKs, and current ones talking to
// an engine without GetDeploymentInfo, call SupportsFeature with a string id ("secrets",
// "resourceReferences", ...). The check reads the SDK's source for both, asks plunge's monitor the same
// questions (deploy.QueryMonitorFeatures), and prints a FEATURE-MISSING line for every feature the SDK asks
// about that plunge answers false to or doesn't know.
package sdkcheck

import (
	"bytes"
	"fmt"
	"io"
	"regexp"
	"slices"
	"sort"
	"strings"
	"unicode"

	"github.com/pulumi/pulumi/pkg/v3/resource/deploy"
	pulumirpc "github.com/pulumi/pulumi/sdk/v3/proto/go"
)

// EnumPrefix is the prefix every ResourceMonitorFeature enum name has in the proto.
const EnumPrefix = "RESOURCE_MONITOR_FEATURE_"

// LegacyIDs are the SupportsFeature string ids upstream's engine knows (the switch in
// deploy.resmon.supportsFeatureID). Upstream froze the list; new features only get an enum value.
var LegacyIDs = []string{
	"aliasSpecs", "deletedWith", "errorHooks", "invokeTransforms", "outputValues", "parameterization",
	"replaceWith", "replacementTrigger", "resourceHooks", "resourceReferences", "secrets", "sendsOptionsToHooks",
	"transforms",
}

// Asked is what an SDK release asks the engine about.
type Asked struct {
	// Legacy holds the string ids the SDK passes to SupportsFeature.
	Legacy []string
	// Enum holds the ResourceMonitorFeature names (RESOURCE_MONITOR_FEATURE_*) the SDK looks for in
	// GetDeploymentInfo's SupportedFeatures.
	Enum []string
}

// Source is one file of an SDK release.
type Source struct {
	Path string
	Data []byte
}

var (
	// SupportsFeature("x"), supportsFeature(monitor, "x"), MonitorSupportsFeature('x'), and Java's
	// SupportsFeatureRequest.newBuilder().setId("x").
	legacyCall = regexp.MustCompile(
		`(?i)supports_?feature\w*\s*\(\s*(?:[\w.]+\s*,\s*)?["']([a-z][A-Za-z0-9]*)["']`)
	legacyBuilder = regexp.MustCompile(`SupportsFeatureRequest[\s\S]{0,120}?setId\(\s*"([a-z][A-Za-z0-9]*)"`)
	// The frozen legacy-id to enum maps the in-repo SDKs keep: `secrets: resproto...RESOURCE_MONITOR_...`,
	// `"secrets": resource_pb2.RESOURCE_MONITOR_...`, `{ "secrets", ResourceMonitorFeature.Secrets }`.
	legacyMapping = regexp.MustCompile(
		`["']?([a-z][A-Za-z0-9]*)["']?\s*[:,=]\s*[\w.]*(?:RESOURCE_MONITOR_FEATURE_[A-Z0-9_]+|ResourceMonitorFeature\.[A-Z]\w*)`)
	// Go, nodejs, python and Java keep the proto's enum value names.
	enumName = regexp.MustCompile(`RESOURCE_MONITOR_FEATURE_([A-Z0-9_]+)`)
	// C# protobuf drops the prefix and Pascal-cases the rest: ResourceMonitorFeature.ResourceReferences.
	csharpEnum = regexp.MustCompile(`ResourceMonitorFeature\.([A-Z][A-Za-z0-9]*)`)
	// Generated protobuf code lists every enum value whether the SDK asks about it or not.
	generatedMarkers = [][]byte{
		[]byte("Generated by the protocol buffer compiler"),
		[]byte("generated by the protocol buffer compiler"),
		[]byte("Code generated by protoc-gen"),
		[]byte("GENERATED CODE -- DO NOT EDIT"),
		[]byte("Generated by the gRPC"),
	}
	sourceSuffixes = []string{".go", ".js", ".ts", ".mjs", ".cjs", ".py", ".cs", ".fs", ".java", ".kt"}
)

// IsGenerated reports whether a file is protobuf or gRPC generated code.
func IsGenerated(data []byte) bool {
	head := data
	if len(head) > 4096 {
		head = head[:4096]
	}
	for _, m := range generatedMarkers {
		if bytes.Contains(head, m) {
			return true
		}
	}
	return false
}

func isSource(path string) bool {
	if strings.HasSuffix(path, ".d.ts") || strings.HasSuffix(path, "_test.go") ||
		strings.HasSuffix(path, ".pb.go") || strings.Contains(path, "_pb2") || strings.HasSuffix(path, "_pb.js") {
		return false
	}
	for _, s := range sourceSuffixes {
		if strings.HasSuffix(path, s) {
			return true
		}
	}
	return false
}

// isTestPath reports paths of tests and mocks, whose feature lists say what a fake monitor answers, not what
// the SDK asks.
func isTestPath(path string) bool {
	p := "/" + strings.ToLower(path)
	base := p[strings.LastIndex(p, "/")+1:]
	return strings.Contains(p, "/tests/") || strings.Contains(p, "/test/") || strings.Contains(p, "/__tests__/") ||
		strings.Contains(p, ".tests/") || strings.Contains(p, "/mocks/") || strings.HasPrefix(base, "mocks.") ||
		strings.HasPrefix(base, "test_") || strings.Contains(base, "_test.") || strings.Contains(base, ".test.") ||
		strings.Contains(base, ".spec.")
}

// Extract reads an SDK release's source files and returns what it asks the engine about. Generated
// protobuf code, tests and mocks are skipped.
func Extract(files []Source) Asked {
	legacy := map[string]bool{}
	enum := map[string]bool{}
	for _, f := range files {
		if !isSource(f.Path) || isTestPath(f.Path) || IsGenerated(f.Data) {
			continue
		}
		for _, m := range legacyCall.FindAllSubmatch(f.Data, -1) {
			legacy[string(m[1])] = true
		}
		for _, m := range legacyBuilder.FindAllSubmatch(f.Data, -1) {
			legacy[string(m[1])] = true
		}
		for _, m := range legacyMapping.FindAllSubmatch(f.Data, -1) {
			legacy[string(m[1])] = true
		}
		for _, m := range enumName.FindAllSubmatch(f.Data, -1) {
			enum[EnumPrefix+string(m[1])] = true
		}
		if strings.HasSuffix(f.Path, ".cs") || strings.HasSuffix(f.Path, ".fs") {
			for _, m := range csharpEnum.FindAllSubmatch(f.Data, -1) {
				enum[EnumPrefix+screamingSnake(string(m[1]))] = true
			}
		}
	}
	// "unspecified" style placeholders aren't features.
	delete(enum, EnumPrefix+"UNSPECIFIED")
	return Asked{Legacy: sortedKeys(legacy), Enum: sortedKeys(enum)}
}

// screamingSnake turns C#'s ResourceReferences back into the proto's RESOURCE_REFERENCES.
func screamingSnake(s string) string {
	var b strings.Builder
	runes := []rune(s)
	for i, r := range runes {
		if i > 0 && unicode.IsUpper(r) &&
			(unicode.IsLower(runes[i-1]) || (i+1 < len(runes) && unicode.IsLower(runes[i+1]))) {
			b.WriteByte('_')
		}
		if i > 0 && unicode.IsDigit(r) && !unicode.IsDigit(runes[i-1]) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}

func sortedKeys(m map[string]bool) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// Verdict is one line of the check's output.
type Verdict struct {
	Kind    string // FEATURE-OK, FEATURE-MISSING, VERSION-OK, VERSION-TOO-OLD, ...
	Lang    string
	Version string
	Subject string // the feature name, or the version detail
	Note    string
}

func (v Verdict) String() string {
	s := strings.Join([]string{v.Kind, v.Lang, v.Version, v.Subject}, " ")
	if v.Note != "" {
		s += " (" + v.Note + ")"
	}
	return s
}

// WriteVerdicts prints one line per verdict.
func WriteVerdicts(w io.Writer, vs []Verdict) error {
	for _, v := range vs {
		if _, err := fmt.Fprintln(w, v.String()); err != nil {
			return err
		}
	}
	return nil
}

// AdvertisedNames turns the monitor's advertised features into proto enum names.
func AdvertisedNames(m deploy.MonitorFeatures) []string {
	names := make([]string, 0, len(m.Advertised))
	for _, f := range m.Advertised {
		names = append(names, f.String())
	}
	sort.Strings(names)
	return names
}

// Diff compares what one SDK release asks against plunge's monitor answers. A legacy id is missing when
// SupportsFeature answers false. An enum feature is missing when GetDeploymentInfo doesn't advertise it,
// and is noted as unknown when plunge's proto has no such enum value at all (the SDK was built against a
// newer proto than plunge's).
func Diff(lang, version string, asked Asked, monitor deploy.MonitorFeatures) []Verdict {
	advertised := AdvertisedNames(monitor)
	var out []Verdict
	for _, id := range asked.Legacy {
		has, known := monitor.Legacy[id]
		switch {
		case !known:
			out = append(out, Verdict{"FEATURE-MISSING", lang, version, id, "SupportsFeature not asked"})
		case has:
			out = append(out, Verdict{"FEATURE-OK", lang, version, id, "SupportsFeature"})
		default:
			out = append(out, Verdict{"FEATURE-MISSING", lang, version, id, "SupportsFeature answers false"})
		}
	}
	for _, name := range asked.Enum {
		_, inProto := pulumirpc.ResourceMonitorFeature_value[name]
		switch {
		case slices.Contains(advertised, name):
			out = append(out, Verdict{"FEATURE-OK", lang, version, name, "GetDeploymentInfo"})
		case !inProto:
			out = append(out, Verdict{
				"FEATURE-MISSING", lang, version, name,
				"unknown to plunge's proto; merge upstream",
			})
		default:
			out = append(out, Verdict{"FEATURE-MISSING", lang, version, name, "not advertised by GetDeploymentInfo"})
		}
	}
	return out
}

// MonitorVerdicts lists every feature plunge's monitor answers false to: legacy ids from ids, and enum
// values in plunge's proto that GetDeploymentInfo doesn't advertise.
func MonitorVerdicts(ids []string, monitor deploy.MonitorFeatures) []Verdict {
	advertised := AdvertisedNames(monitor)
	var out []Verdict
	for _, id := range ids {
		if !monitor.Legacy[id] {
			out = append(out, Verdict{"MONITOR-FALSE", "plunge", "-", id, "SupportsFeature"})
		}
	}
	var enumNames []string
	for name, n := range pulumirpc.ResourceMonitorFeature_value {
		if n >= 0 {
			enumNames = append(enumNames, name)
		}
	}
	sort.Strings(enumNames)
	for _, name := range enumNames {
		if !slices.Contains(advertised, name) {
			out = append(out, Verdict{"MONITOR-FALSE", "plunge", "-", name, "GetDeploymentInfo"})
		}
	}
	return out
}
